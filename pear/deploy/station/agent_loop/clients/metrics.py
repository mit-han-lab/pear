import math
import time
from enum import StrEnum
from typing import Any

from pear.deploy.station.agent_loop.clients.schemas import Usage


class RequestStatus(StrEnum):
    """Where a model request stands, each by the word its performance events carry."""

    STREAMING = "streaming"  # its answer still comes
    COMPLETED = "completed"  # it ended with the answer
    INTERRUPTED = "interrupted"  # a stop ended it
    FAILED = "failed"  # it ended without an answer


class Performance:
    """The timings and the decode throughput of one model request, as its performance events hold them."""

    @staticmethod
    def report(
        provider: str,
        start_time: float,
        first_output_s: float | None,
        usage: Usage,
        *,
        status: RequestStatus = RequestStatus.COMPLETED,
    ) -> dict[str, Any]:
        """Returns the timings a client observed of a request that began at ``start_time``."""
        elapsed_s = time.monotonic() - start_time
        output_tokens = usage.get("output")

        return {
            "backend": provider,
            "first_visible_output_s": first_output_s,
            "elapsed_s": elapsed_s,
            "output_tokens": output_tokens,
            "output_throughput_tps": output_tokens / elapsed_s if output_tokens is not None and elapsed_s > 0 else None,
            "final": status != RequestStatus.STREAMING,
            "status": status.value,
        }

    @staticmethod
    def decode_rate(samples: list[tuple[Any, Any]]) -> dict[str, float | None]:
        """Returns the decode rate on the server's clock of (tokens, milliseconds) samples, None for both of its
        numbers when a sample is unusable."""
        no_rate = {"decode_throughput_tps": None, "decode_time_s": None}
        if not samples:
            return no_rate

        for tokens, milliseconds in samples:
            if (
                type(milliseconds) not in (int, float)
                or not math.isfinite(milliseconds)
                or milliseconds <= 0
                or type(tokens) is not int
                or tokens <= 1
            ):
                return no_rate

        seconds = sum(milliseconds for _, milliseconds in samples) / 1000

        # the first token ends the prefill: only the others are decoded
        return {
            "decode_throughput_tps": sum(tokens - 1 for tokens, _ in samples) / seconds,
            "decode_time_s": seconds,
        }


class TokenRate:
    """The tokens a second, on the client's clock, between the first and the last usage report of each request."""

    def __init__(self) -> None:
        # request id -> ((the first count, when it came), (the last count, when it came))
        self._samples: dict[str, tuple[tuple[int, float], tuple[int, float]]] = {}

    def add(self, request_id: str, token_count: Any, received_at: float) -> None:
        """Takes the tokens a request has generated by ``received_at``; a count that is no whole number above zero is
        left out."""
        if type(token_count) is not int or token_count <= 0:
            return

        if request_id not in self._samples:
            self._samples[request_id] = ((token_count, received_at), (token_count, received_at))
        elif token_count > self._samples[request_id][1][0]:
            self._samples[request_id] = (self._samples[request_id][0], (token_count, received_at))

    def tokens_per_second(self) -> float | None:
        """Returns the rate over the requests whose reports span some time, None when no request's do."""
        spans = [
            (last_report[0] - first_report[0], last_report[1] - first_report[1])
            for first_report, last_report in self._samples.values()
            if last_report[1] > first_report[1]
        ]
        seconds = sum(span for _, span in spans)

        return sum(tokens for tokens, _ in spans) / seconds if seconds else None
